/** Whether a word starts with a vowel, so "de" and "que" before it elide: "d’Ana", "qu’Oikome". */
const vowel = (word: string) => /^[aeiouyàâäéèêëîïôöùûü]/i.test(word);
const de = (word: string) => (vowel(word) ? `d’${word}` : `de ${word}`);
const que = (word: string) => (vowel(word) ? `qu’${word}` : `que ${word}`);
/** In Activity the owner is "Vous" (common.you), and the verb agrees: "Vous avez lu", "Sam a lu". */
const isYou = (who: string) => who === "Vous";
const has = (who: string) => `${who} ${isYou(who) ? "avez" : "a"}`;

