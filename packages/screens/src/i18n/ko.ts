// Numbers as Korean writes them; called `num` because many values below are themselves `n`.
const num = count("ko");

/**
 * How a word's last sound ends as Korean reads it, for the particle after a
 * name given at runtime: "" (a vowel), "ㄹ", or "x" (another consonant).
 * Hangul by its last syllable, digits as read (일, 삼, 육…), Latin letters by
 * a few common endings (Sam, Bob, Nick, Jill; Ana, Alex, Claude Code).
 */
function coda(word: string): "" | "ㄹ" | "x" {
  const w = word.trim();
  const code = w.charCodeAt(w.length - 1);
  if (code >= 0xac00 && code <= 0xd7a3) {
    const final = (code - 0xac00) % 28;
    return final === 0 ? "" : final === 8 ? "ㄹ" : "x";
  }
  if (/([178]|l)$/i.test(w)) return "ㄹ";
  if (/([036]|m|n|ng|ck|b|p)$/i.test(w)) return "x";
  return "";
}

const after = (word: string, consonant: string, vowel: string) => word + (coda(word) === "" ? vowel : consonant);
/** Sam이, Ana가; 나 is 내가. */
const iGa = (word: string) => (word === "나" ? "내가" : after(word, "이", "가"));
const eulReul = (word: string) => after(word, "을", "를");
const eunNeun = (word: string) => after(word, "은", "는");
/** Sam으로, Ana로, Jill로. */
const euro = (word: string) => word + (coda(word) === "x" ? "으로" : "로");
/** Contacts named in a sentence: "Sam 님", "Sam 님, Bob 님". */
const people = (names: string[]) => names.map((name) => `${name} 님`).join(", ");

