/** Text, as a language writes it: English's literal words widened to any string. */
type Words<T> = T extends (...args: infer A) => unknown
  ? (...args: A) => string
  : T extends object
    ? { [K in keyof T]: Words<T[K]> }
    : string;

/** The words of one language: the same keys, and functions taking the same values, as English. */
export type Strings = Words<typeof en>;

/** A node's sentence as a sentence: "this has ended" reads "This has ended." */
export function sentence(text: string): string {
  const m = text.trim();
  return m ? m.charAt(0).toUpperCase() + m.slice(1) + (/[.!?]$/.test(m) ? "" : ".") : m;
}
