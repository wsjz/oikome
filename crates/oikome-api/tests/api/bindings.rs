//! `packages/api/src/index.ts` is generated from the API's types and kept in
//! the repository. This test fails when it is out of date;
//! `UPDATE_BINDINGS=1 cargo t --test api -- bindings` rewrites it.

use std::path::Path;

use oikome_api::*;
use ts_rs::{Config, TS};

const HEADER: &str = "\
// Copyright 2025 The Oikome Authors
// SPDX-License-Identifier: Apache-2.0
//
// Types of the Oikome API (crates/oikome-api/src/types.rs), generated by
// `UPDATE_BINDINGS=1 cargo t --test api -- bindings`. Do not edit.
";

fn bindings() -> String {
    // JSON carries integers as numbers; ids and times stay well below 2^53.
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(HEADER);
    macro_rules! declare {
        ($($t:ty),* $(,)?) => {
            $(
                out.push('\n');
                if let Some(docs) = <$t as TS>::docs() {
                    out.push_str(&docs);
                }
                out.push_str("export ");
                out.push_str(&<$t as TS>::decl(&cfg));
                out.push('\n');
            )*
        };
    }
    declare!(
        ErrorCode,
        ApiError,
        Empty,
        AddExamples,
        NodeInfo,
        NodeName,
        HomeCard,
        HomeCards,
        RecoveryKey,
        SpaceKind,
        SpaceSummary,
        NewSpace,
        StorageType,
        StorageSummary,
        NewStorage,
        DefaultStorage,
        StorageRef,
        StartDropbox,
        FinishDropbox,
        DropboxApp,
        DropboxSignIn,
        GoogleReturn,
        StartGoogleDrive,
        GoogleApp,
        GoogleSignIn,
        SourceKind,
        SourceSummary,
        NewSource,
        PauseSource,
        SetSourceEvery,
        SourceRun,
        SourceRef,
        FoundPlace,
        FolderRef,
        FolderListing,
        FolderEntry,
        SpaceRef,
        RelationKind,
        TableSummary,
        ReadRows,
        ReadRow,
        Search,
        SearchResults,
        SearchHit,
        SearchMark,
        SearchSkipped,
        SearchSkip,
        RunSql,
        SqlDone,
        Contact,
        ContactInput,
        DidRef,
        RemovedContact,
        ShareSpace,
        ShareAccess,
        ShareStatus,
        NewShare,
        InviteCode,
        InviteRef,
        AcceptInvite,
        InviteKind,
        Invite,
        AcceptedInvite,
        Lending,
        LentTo,
        SetLending,
        LendingSaved,
        LendInvite,
        ReachPolicy,
        ReachChoice,
        Reachable,
        OpenForKind,
        OpenFor,
        Network,
        SetNetwork,
        BorrowStatus,
        Borrowed,
        BorrowedRef,
        UseBorrowed,
        BorrowedJobsOf,
        BorrowedJobs,
        SentJob,
        DailyTotalsOf,
        DailyTotals,
        DayTotal,
        StayedHere,
        InPlace,
        ViewInPlace,
        AddInPlaceFiles,
        AddInPlaceFolder,
        ImportFile,
        ImportFiles,
        ListFiles,
        FileListing,
        FileFolder,
        FileSort,
        FileKind,
        ContentView,
        ContentCapabilities,
        FileContent,
        FileItem,
        FileRef,
        ReadFileRows,
        ShowFolder,
        PluginShape,
        PluginColumn,
        Plugin,
        PluginText,
        InstallPlugin,
        PluginFolder,
        PluginCollections,
        PluginRef,
        PluginRead,
        AssistantApp,
        Assistant,
        ConnectAssistant,
        AssistantConnected,
        AssistantCollections,
        AssistantRef,
        ReadableCollection,
        ReadableTable,
        Share,
        ListShares,
        ShareRef,
        RevokedShare,
        ListAccess,
        AccessOutcome,
        AccessWho,
        AccessItem,
    );
    out.lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

#[test]
fn typescript_bindings_are_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/api/src/index.ts");
    let generated = bindings();
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &generated).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "packages/api/src/index.ts is out of date; run \
         UPDATE_BINDINGS=1 cargo t --test api -- bindings"
    );
}
